"""Assignment-scoped exports for the adviser and PIT instructor workspaces."""

from django.shortcuts import get_object_or_404
from django.utils import timezone
from rest_framework.exceptions import PermissionDenied, ValidationError
from rest_framework.permissions import IsAuthenticated
from rest_framework.views import APIView

from academic_period_management.services import active_semester
from authentication_access_control.scopes import section_instructor_section_filters
from defense.scheduler.models import DefenseSchedule
from grading.grades.models import TeamGrade
from repository.deliverables.services import current_stage_for_team, stage_payload
from reports.catalog_reports import column, dataset, name, render_pdf
from reports.export_formatters import handle_export_or_preview
from student_teams.models import StudentTeam


def faculty_teams(request):
    """The workspace decides the assignment rule, even for multi-role faculty."""
    workspace = request.query_params.get('workspace')
    user = request.user
    if getattr(user, 'role', None) != 'faculty' or workspace not in ('adviser', 'pit_instructor'):
        raise PermissionDenied('Choose an assigned faculty workspace to export this report.')
    teams = StudentTeam.objects.select_related('semester', 'leader', 'adviser').prefetch_related(
        'memberships__student'
    )
    if workspace == 'adviser':
        if not user.is_adviser:
            raise PermissionDenied('Only assigned advisers can export this report.')
        return teams.filter(level__icontains='Capstone', adviser=user), workspace
    if not user.section_instructor_assignments.filter(is_active=True).exists():
        raise PermissionDenied('Only assigned PIT instructors can export this report.')
    return teams.filter(level__icontains='PIT').filter(section_instructor_section_filters(user)), workspace


def selected_stage(team, requested):
    stage = requested or current_stage_for_team(team) or ''
    if not stage:
        return ''
    if requested:
        if team.is_capstone:
            from defense.stages.models import DefenseStage
            valid = DefenseStage.objects.filter(label=stage, is_active=True).exists()
        else:
            from defense.scheduler.models import PitEventGradingConfig
            valid = PitEventGradingConfig.objects.filter(semester=team.semester, year_level=team.year_level, event_name=stage).exists()
        if not valid:
            raise ValidationError({'stage': 'Select a configured stage or event for this team.'})
    return stage


def schedule_for(team, stage):
    if not stage:
        return None
    schedules = DefenseSchedule.objects.filter(
        team=team, project_version=team.project_version,
        status__in=[DefenseSchedule.STATUS_SCHEDULED, DefenseSchedule.STATUS_DONE],
    ).select_related('defense_stage').order_by('-scheduled_date', '-start_time')
    schedules = schedules.filter(defense_stage__label=stage) if team.is_capstone else schedules.filter(event_name=stage)
    return schedules.first()


def published_grade_for(team, stage):
    if not stage:
        return None
    return TeamGrade.objects.filter(
        team=team, semester=team.semester, project_version=team.project_version,
        stage_label=stage, status=TeamGrade.STATUS_PUBLISHED,
    ).order_by('-updated_at', '-id').first()


def schedule_text(schedule):
    if not schedule:
        return 'Not scheduled'
    return f'{schedule.scheduled_date:%Y-%m-%d} {schedule.start_time:%I:%M %p} - {schedule.room} ({schedule.status.title()})'


def export(request, spec, filename, metadata):
    generated_by = name(request.user)
    metadata = [*metadata, {'label': 'Generated by', 'value': generated_by},
                {'label': 'Generated on', 'value': timezone.localtime().strftime('%Y-%m-%d %I:%M %p')}]
    return handle_export_or_preview(
        request.query_params.get('export_format', 'pdf'), spec['title'],
        'Assigned faculty workspace record', [{'label': 'Teams', 'value': str(len(spec['rows']))}],
        metadata, spec['columns'], spec['rows'], filename,
        lambda: render_pdf(spec, metadata, generated_by, False, None),
        sections=spec.get('sections'), generated_by=generated_by,
    )


class FacultyTeamsOverviewView(APIView):
    permission_classes = [IsAuthenticated]

    def get(self, request):
        teams, workspace = faculty_teams(request)
        semester = active_semester()
        if semester:
            teams = teams.filter(semester=semester)
        raw_ids = request.query_params.get('team_ids', '')
        if not raw_ids or len(raw_ids) > 2000:
            raise ValidationError({'team_ids': 'Select teams from the current filtered list.'})
        parts = raw_ids.split(',')
        if len(parts) > 200 or any(not part.isdigit() for part in parts):
            raise ValidationError({'team_ids': 'Select valid team IDs.'})
        ids = {int(part) for part in parts}
        if not ids or 0 in ids:
            raise ValidationError({'team_ids': 'Select at least one team.'})
        teams = list(teams.filter(id__in=ids).order_by('name'))
        if {team.id for team in teams} != ids:
            raise PermissionDenied('The selected list contains a team outside your assignment.')
        requested_stage = request.query_params.get('stage', '').strip()
        rows = []
        for team in teams:
            stage = selected_stage(team, requested_stage)
            progress = stage_payload(team, stage) if stage else {}
            schedule = schedule_for(team, stage)
            grade = published_grade_for(team, stage)
            rows.append({
                'team': team.name, 'project': team.project_title, 'section': team.section,
                'stage': stage or 'Not configured',
                'clearance': f"{progress.get('required_uploaded', 0)}/{progress.get('required_total', 0)} uploaded; "
                             + ('cleared' if progress.get('required_complete') else 'in progress'),
                'schedule': schedule_text(schedule),
                'grade': str(grade.final_grade) if grade and grade.final_grade is not None else 'Not published',
            })
        spec = dataset('Assigned Teams Overview', [
            column('team', 'Team'), column('project', 'Project'), column('section', 'Section'),
            column('stage', 'Stage / Event'), column('clearance', 'Required files'),
            column('schedule', 'Schedule'), column('grade', 'Published grade'),
        ], rows)
        return export(request, spec, 'DefenSYS_Assigned_Teams_Overview', [
            {'label': 'Workspace', 'value': 'Capstone Adviser' if workspace == 'adviser' else 'PIT Instructor'},
            {'label': 'Academic period', 'value': semester.display_name if semester else 'No active semester'},
            {'label': 'Teams', 'value': len(rows)},
        ])


class FacultyTeamSummaryView(APIView):
    permission_classes = [IsAuthenticated]

    def get(self, request, team_id):
        teams, workspace = faculty_teams(request)
        team = get_object_or_404(teams, pk=team_id)
        stage = selected_stage(team, request.query_params.get('stage', '').strip())
        progress = stage_payload(team, stage) if stage else {}
        schedule = schedule_for(team, stage)
        grade = published_grade_for(team, stage)
        roster = [{'student': name(m.student), 'role': 'Leader' if m.student_id == team.leader_id else 'Member'}
                  for m in team.memberships.all()]
        files = []
        show_post = progress.get('endorsed') or progress.get('has_active_schedule') or \
            progress.get('has_done_schedule')
        visible_files = [*progress.get('pre', []), *(progress.get('post', []) if show_post else [])]
        for item in visible_files:
            submission = item.get('submission') or {}
            status = submission.get('status', 'Not submitted') if isinstance(submission, dict) else 'Not submitted'
            if item.get('type') == 'post' and not item.get('can_upload') and status == 'Not submitted':
                status = 'Locked until defense is done'
            files.append({
                'file': item.get('label') or item.get('name') or item.get('id') or 'File',
                'timing': 'After defense' if item.get('type') == 'post' else
                          ('Before defense' if item.get('requirement_timing') == 'defense' else 'Before endorsement'),
                'status': status,
            })
        spec = dataset('Assigned Team Summary', [
            column('item', 'Summary item'), column('value', 'Current value'),
        ], [
            {'item': 'Team', 'value': team.name},
            {'item': 'Project', 'value': team.project_title},
            {'item': 'Stage / event', 'value': stage or 'Not configured'},
            {'item': 'Required files', 'value': f"{progress.get('required_uploaded', 0)}/{progress.get('required_total', 0)} uploaded; "
             + ('cleared' if progress.get('required_complete') else 'in progress')},
            {'item': 'Schedule', 'value': schedule_text(schedule)},
            {'item': 'Published grade', 'value': str(grade.final_grade) if grade and grade.final_grade is not None else 'Not published'},
        ], sections=[
            dataset('Team roster', [column('student', 'Student'), column('role', 'Role')], roster),
            dataset('Deliverables for selected stage', [column('file', 'File'), column('timing', 'Due'),
                                                       column('status', 'Submission status')], files),
        ])
        return export(request, spec, f'DefenSYS_Team_{team.id}_Summary', [
            {'label': 'Workspace', 'value': 'Capstone Adviser' if workspace == 'adviser' else 'PIT Instructor'},
            {'label': 'Academic period', 'value': team.semester.display_name},
            {'label': 'Team', 'value': team.name},
            {'label': 'Section', 'value': team.section},
        ])
